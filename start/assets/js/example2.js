"use strict";
// Add
function add(a, b) {
    return a + b;
}
// Subtract
function subtract(a, b) {
    return a - b;
}
// Multiply
function multiply(a, b) {
    return a * b;
}
// Test the functions
console.log("add(2, 3) =", add(2, 3));
console.log("subtract(10, 4) =", subtract(10, 4));
console.log("multiply(5, 6) =", multiply(5, 6));
